def generate_terraform_template(external_id: str, aws_account_id: str, platform_assume_role_arn: str = "arn:aws:iam::783764605244:role/CloudCostAssumeRole") -> str:
    """Returns Terraform HCL code snippet to deploy scanner role in customer AWS account."""
    return f'''# Cloud Cost Intelligence — Cross-Account FinOps Scanner Role
# Deploy in your customer AWS account ({aws_account_id})

terraform {{
  required_providers {{
    aws = {{
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }}
  }}
}}

resource "aws_iam_role" "cloudcost_scanner" {{
  name        = "CloudCostScannerRole"
  description = "Read-only role assumed by Cloud Cost Intelligence for cost analytics"

  assume_role_policy = jsonencode({{
    Version = "2012-10-17"
    Statement = [
      {{
        Sid    = "CloudCostAssumeRole"
        Effect = "Allow"
        Principal = {{
          AWS = "{platform_assume_role_arn}"
        }}
        Action = "sts:AssumeRole"
        Condition = {{
          StringEquals = {{
            "sts:ExternalId" = "{external_id}"
          }}
        }}
      }}
    ]
  }})

  tags = {{
    CreatedBy = "CloudCostIntelligence"
    Purpose   = "FinOps-Cost-Monitoring"
  }}
}}

resource "aws_iam_role_policy_attachment" "security_audit" {{
  role       = aws_iam_role.cloudcost_scanner.name
  policy_arn = "arn:aws:iam::aws:policy/SecurityAudit"
}}

resource "aws_iam_role_policy_attachment" "read_only" {{
  role       = aws_iam_role.cloudcost_scanner.name
  policy_arn = "arn:aws:iam::aws:policy/ReadOnlyAccess"
}}

output "role_arn" {{
  description = "Paste this ARN into Cloud Cost Intelligence to complete connection"
  value       = aws_iam_role.cloudcost_scanner.arn
}}
'''


