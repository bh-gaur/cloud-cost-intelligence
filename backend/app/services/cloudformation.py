def get_trust_policy(external_id: str, platform_assume_role_arn: str = "arn:aws:iam::783764605244:role/CloudCostAssumeRole") -> Dict[str, Any]:
    """Generates IAM Trust Policy restricting AssumeRole access to the platform and tenant ExternalID."""
    return {
        "Version": "2012-10-17",
        "Statement": [
            {
                "Sid": "CloudCostAssumeRole",
                "Effect": "Allow",
                "Principal": {
                    "AWS": platform_assume_role_arn
                },
                "Action": "sts:AssumeRole",
                "Condition": {
                    "StringEquals": {
                        "sts:ExternalId": external_id
                    }
                }
            }
        ]
    }


